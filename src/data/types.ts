import type { Dish } from "@/lib/matching";
import type { Confidence } from "@/lib/nutrition";

export type VenueKind = "Café" | "Restaurant" | "Takeaway" | "Juice bar";

export type Venue = {
  id: string;
  name: string;
  kind: VenueKind;
  cuisine: string;
  address: string;
  lat: number;
  lng: number;
  confidence: Confidence;
  /** Google Places id, for venues found by the ingest pipeline. */
  placeId?: string;
  website?: string;
  /** Where the menu was read from (a URL, or "manual" for a file someone added). */
  menuSource?: string;
};

export type Area = { name: string; lat: number; lng: number; radiusKm: number };

/** Everything the app shows. Generated by `npm run ingest`, or the built-in sample. */
export type Catalogue = {
  version: 1;
  generatedAt: string | null;
  area: Area;
  venues: Venue[];
  dishes: Dish[];
};
